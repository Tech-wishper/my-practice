/*2018年FISM（世界魔术大会）近景总冠军简纶廷的表演中有一个情节：以桌面上一根带子为界，当他将纸牌从带子的一边推到另一边时，纸牌会变成硬币；把硬币推回另一边会变成纸牌。
这里我们假设纸牌会变成等量的硬币，而硬币变成纸牌时，纸牌的数量会加倍。那么给定纸牌的初始数量，当他来回推了 N 次（来/回各算一次）后，手里拿的是纸牌还是硬币？数量是多少？
输入格式：
输入在一行里给出两个正整数，分别是纸牌的初始数量和魔术师推送的次数。这里假设初始状态下魔术师手里全是纸牌。
输出格式：
如果最后魔术师手里是纸牌，输出 0 和纸牌数量；如果是硬币，则输出 1 和硬币数量。数字间须有 1 个空格。题目保证结果数值不超出整型范围（即 2
31
 −1）。
输入样例 1：
3 7
输出样例 1：
1 24
输入样例 2：
8 4
输出样例 2：
0 32
*/
#include <stdio.h>

int main(){
    int i, n;

    // 【重要】读入两个正整数：
    //   第一个 i = 纸牌的初始数量
    //   第二个 n = 推送的总次数（来/回各算一次）
    // 注意：两个 %d 之间有一个空格，表示输入时可以隔任意多个空格，
    //       这是标准写法，别漏掉里面的空格。
    scanf("%d %d", &i, &n);

    // num 表示"当前手里的数量"。
    // 【易错】因为翻倍是累加的，所以 num 必须在循环外声明一次，
    //        千万不要写在循环体内——否则每轮都会被重新赋值，累加白做。
    int num = i;

    /*
      核心规律（务必理解）：
        第 1 次推（去）：纸牌 → 硬币，数量不变
        第 2 次推（回）：硬币 → 纸牌，数量翻倍
        第 3 次推（去）：纸牌 → 硬币，数量不变
        第 4 次推（回）：硬币 → 纸牌，数量翻倍
        ……
      也就是说：只有"偶数次推送"时数量才会翻倍。

      n 次推送里，偶数次有 n/2 个（向下取整），
      所以一共翻倍 n/2 次。

      【易错点 1】用 n/2 而不是 n：
                因为只有一半的次数（偶数次）会翻倍，
                写成 n 次就翻倍太多了。
      【易错点 2】整数除法 n/2 本身就会向下取整：
                n=7 时 7/2=3，正好是偶数次数(2,4,6)的个数，直接用它即可。
    */
    for(int k = 0; k < n/2; k++){
        num = num * 2;          // 每循环一次，数量翻一倍
    }

    /*
      判断最后手里是纸牌还是硬币：
        初始状态是纸牌（编号 0）。
        奇数次的推送 → 最终停在"硬币"（输出 1）
        偶数次的推送 → 最终回到"纸牌"（输出 0）

      【易错点 3】判断的是 n 的奇偶，不是 num 的奇偶，
                也不是 n/2 的奇偶！很多人一看到"翻倍"就以为
                要判断数量，其实类型只看推送次数的奇偶。
    */
    if(n % 2 == 0){
        // 偶数次推送 → 纸牌，输出 0 和数量
        printf("0 %d", num);
    }else{
        // 奇数次推送 → 硬币，输出 1 和数量
        printf("1 %d", num);
    }

    return 0;
}
