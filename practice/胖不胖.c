/*据说一个人的标准体重应该是其身高（单位：厘米）减去100、再乘以0.9所得到的公斤数。真实体重与标准体重误差在10%以内都是完美身材（即 | 真实体重 − 标准体重 | < 标准体重×10%）。已知市斤是公斤的两倍。现给定一群人的身高和实际体重，请你告诉他们是否太胖或太瘦了。

输入格式：
输入第一行给出一个正整数N（≤ 20）。随后N行，每行给出两个整数，分别是一个人的身高H（120 < H < 200；单位：厘米）和真实体重W（50 < W ≤ 300；单位：市斤），其间以空格分隔。

输出格式：
为每个人输出一行结论：如果是完美身材，输出You are wan mei!；如果太胖了，输出You are tai pang le!；否则输出You are tai shou le!
*/
#include <stdio.h>   // 打开"输入输出"工具箱，才能用 scanf、printf
#include <math.h>    // 打开"数学"工具箱，才能用下面那个 fabs（求绝对值）

int main() {                       // 程序从这里开始跑
    int N;                         // 准备一个整数盒子 N：等下要输入"一共几组数据"
    scanf("%d", &N);               // 读入组数，存进 N（比如输入 3，就是有 3 个人）

    for (int i = 0; i < N; i++) {  // 循环 N 次，每次处理一个人
        int h, w;                  // 两个整数盒子：h=身高(cm)，w=体重(斤)
        scanf("%d %d", &h, &w);    // 读身高和体重（注意：顺序不能反）

        // 标准体重公式：标准值 = (身高 - 100) × 0.9
        // 比如身高 170cm，标准体重 =(170-100)*0.9 = 63
        double mw = (h - 100) * 0.9;

        // w/2.0：把体重的"斤"换算成"公斤"，好跟标准值比较
        // fabs(x) = 求 x 的绝对值，即不管正负都取正的
        // mw * 0.1：标准体重的 10%，这是"允许偏差范围"
        if (fabs(w / 2.0 - mw) < mw * 0.1) {
            // 条件：实际体重与标准体重相差 < 标准值的10%
            // 也就是"不胖不瘦"，在合理范围内
            printf("You are wan mei!\n");      // 完美！
        } else if (w / 2.0 > mw) {
            // 上一条件不满足，说明偏差超过10%
            // 再看是偏重还是偏轻：实际 > 标准 → 偏胖
            printf("You are tai pang le!\n");  // 太胖了！
        } else {
            // 既不是完美，又不是偏胖，那只能是 → 偏瘦
            printf("You are tai shou le!\n");  // 太瘦了！
        }
    }
    return 0;   // 程序正常结束，返回 0
}
//注意fabs是取绝对值的意思