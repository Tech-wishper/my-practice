/*小强在统计一个小区里居民的出生年月，但是发现大家填写的生日格式不统一，例如有的人写 199808，有的人只写 9808。有强迫症的小强请你写个程序，把所有人的出生年月都整理成 年年年年-月月 格式。对于那些只写了年份后两位的信息，我们默认小于 22 都是 20 开头的，其他都是 19 开头的。
输入格式：
输入在一行中给出一个出生年月，为一个 6 位或者 4 位数，题目保证是 1000 年 1 月到 2021 年 12 月之间的合法年月。
输出格式：
在一行中按标准格式 年年年年-月月 将输入的信息整理输出。
*/
#include <stdio.h>

int main() {
    int i;                 // i = 输入的出生年月（可能是 4 位，也可能是 6 位）
    int y, m;              // y = 年，m = 月

    scanf("%d", &i);       // 读入这个数

    if (i > 9999) {              // 大于 9999 → 说明是 6 位数
        y = i / 100;             // 6 位数：前 4 位是年（除以100砍掉后2位）
        m = i % 100;             // 后 2 位是月（对100取余）
    } else {                     // 否则是 4 位数：只有年份后两位 + 月份
        m = i % 100;             // 后 2 位是月
        if (i / 100 < 22) {      // 年份后两位 < 22 → 20 开头
            y = 2000 + i / 100;
        } else {                 // 后两位 ≥ 22 → 19 开头
            y = 1900 + i / 100;
        }
    }

    printf("%d-%02d\n", y, m);   // 统一输出：年-月
    return 0;
}
