/*专家通过多组情侣研究数据发现，最佳的情侣身高差遵循着一个公式：（女方的身高）×1.09 =（男方的身高）。如果符合，你俩的身高差不管是牵手、拥抱、接吻，都是最和谐的差度。

下面就请你写个程序，为任意一位用户计算他/她的情侣的最佳身高。

输入格式：
输入第一行给出正整数N（≤10），为前来查询的用户数。随后N行，每行按照“性别 身高”的格式给出前来查询的用户的性别和身高，其中“性别”为“F”表示女性、“M”表示男性；“身高”为区间 [1.0, 3.0] 之间的实数。

输出格式：
对每一个查询，在一行中为该用户计算出其情侣的最佳身高，保留小数点后2位。

输入样例：
2
M 1.75
F 1.8
输出样例：
1.61
1.96
*/
#include <stdio.h>   // 引入标准输入输出库，才能使用 scanf 和 printf

int main()           // 主函数，程序从这里开始执行
{
    int N;               // N：一共有多少组数据（要处理几个人）
    int i = 0;           // i：循环计数器，从 0 开始，记录已经处理了几组
    char sex;            // sex：性别，用一个字符表示，'M' 是男，'F' 是女
    double hight;        // hight：身高，double 表示小数，精度比 float 更高

    scanf("%d", &N);     // 先读入数据组数 N

    while (i < N)        // 只要还没处理满 N 组，就一直循环
    {
        // 读入性别和身高：
        // %c 前加一个空格，是为了"吃掉"缓冲区里的空白字符（空格、回车等）
        // 否则上一行结尾的回车会被当成性别的输入，导致出错
        scanf(" %c %lf", &sex, &hight);

        if (sex == 'M')  // 如果性别是男（M）
        {
            // 男生：用身高 ÷ 1.09，printf 中 %.2lf 表示保留两位小数
            printf("%.2lf\n", hight / 1.09);
        }
        else if (sex == 'F')  // 否则如果性别是女（F）
        {
            // 女生：用身高 × 1.09
            printf("%.2lf\n", hight * 1.09);
        }

        i++;             // 处理完一组，计数器加 1，准备处理下一组
    }

    return 0;            // 程序正常结束，返回 0
}
