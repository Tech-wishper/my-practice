/*BCD数是用一个字节来表达两位十进制的数，每四个比特表示一位。所以如果一个BCD数的十六进制是0x12，它表达的就是十进制的12。但是小明没学过BCD，把所有的BCD数都当作二进制数转换成十进制输出了。于是BCD的0x12被输出成了十进制的18了！
现在，你的程序要读入这个错误的十进制数，然后输出正确的十进制数。提示：你可以把18转换回0x12，然后再转换回12。
输入格式：
输入在一行中给出一个[0, 153]范围内的正整数，保证能转换回有效的BCD数，也就是说这个整数转换成十六进制时不会出现A-F的数字。
输出格式：
输出对应的十进制数。
输入样例：
18
输出样例：
12*/
#include <stdio.h>

int main(){
    int n;
    scanf("%d", &n);              // 读入错误值，比如 18

    /*
      思路：
      输入的 N 是小明把 BCD 数当成"十六进制"读出来的结果，
      所以 N 的十六进制各位，正好就是正确 BCD 数的各位。
      举例：
        BCD 12 → 0x12 → 小明错读成 18
        BCD 25 → 0x25 → 小明错读成 37

      做法：把 N 按十六进制拆成高位和低位，再用十进制权重拼回去。
        18 的高位 = 18 / 16 = 1
        18 的低位 = 18 % 16 = 2
        拼成十进制 = 1 × 10 + 2 = 12

      注意：
        输入 ≤ 153 = 0x99，最多两位十六进制，所以只拆两位就够了。
        （类比：取十进制各位用 /10、%10；这里用 /16、%16，只是基数不同）
    */

    int high = n / 16;            // 十六进制高位
    int low  = n % 16;            // 十六进制低位

    int result = high * 10 + low; // 用十进制权重拼回正确值

    printf("%d\n", result);
    return 0;
}
