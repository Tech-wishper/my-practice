/*你永远叫不醒一个装睡的人 —— 但是通过分析一个人的呼吸频率和脉搏，你可以发现谁在装睡！医生告诉我们，正常人睡眠时的呼吸频率是每分钟15-20次，脉搏是每分钟50-70次。下面给定一系列人的呼吸频率与脉搏，请你找出他们中间有可能在装睡的人，即至少一项指标不在正常范围内的人。
输入格式：
输入在第一行给出一个正整数（）。随后行，每行给出一个人的名字（仅由英文字母组成的、长度不超过3个字符的串）、其呼吸频率和脉搏（均为不超过100的正整数）。
输出格式：
按照输入顺序检查每个人，如果其至少一项指标不在正常范围内，则输出其名字，每个名字占一行。
*/
#include <stdio.h>

int main() {
    int i, n;
    scanf("%d", &i);              // 读入"病人总数"，存进 i（比如输入 3，就是有 3 个人）

    for (n = 0; n < i; n++) {     // 循环 i 次，每次处理一个病人
        int huxi, maibo;          // huxi=呼吸次数，maibo=脉搏次数（都是整数）
        char name[10];            // 存名字的字符数组，最多放 9 个字符 + 结尾符

        scanf("%s %d %d", name, &huxi, &maibo);  // 按顺序读：名字、呼吸、脉搏
                                                 // 注意：name 前面不能加 &，huxi/maibo 必须加 &

        // 判断是否"异常"：只要有一项超标，就算异常
        // 正常范围 → 呼吸 15~20，脉搏 50~70
        // 任意一项 <下限 或 >上限，就要挂号
        if ((huxi < 15) || (huxi > 20) || (maibo < 50) || (maibo > 70)) {
            printf("%s\n", name);  // 异常 → 输出这个名字（每个名字占一行）
        }
        // 正常的病人不用输出，直接跳过
    }

    return 0;
}
